# GCD of max and min array elements ====================================================

# Iterative 
class Gcd:
	def __init__(self, arr):
		self.arr = arr

	def gcd(self):

          a = min(self.arr)
          b = max (self.arr)

          while b:
               a,b= b, a%b

          return a


